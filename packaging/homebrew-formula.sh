#!/usr/bin/env bash
# Render the Homebrew formula for one release.
#
#   homebrew-formula.sh <version> <dir-with-checksums>
#
# The directory holds the .sha256 files the release workflow attaches, one per
# archive. Homebrew gets a binary formula: the archives are already built,
# attested and static on Linux, so there is nothing to compile and no Rust
# toolchain on the user's machine.
set -euo pipefail

version=$1
checksum_dir=$2

sha256_of() {
  local file="${checksum_dir}/mcp-ctl-${version}-$1.tar.gz.sha256"
  [ -f "$file" ] || {
    printf 'missing checksum: %s\n' "$file" >&2
    exit 1
  }
  awk '{print $1}' "$file"
}

url_of() {
  printf 'https://github.com/erikenz/mcp-ctl/releases/download/v%s/mcp-ctl-%s-%s.tar.gz' \
    "$version" "$version" "$1"
}

cat <<EOF
# Generated by packaging/homebrew-formula.sh on every release. Do not edit.
class McpCtl < Formula
  desc "One config file for all your MCP servers"
  homepage "https://github.com/erikenz/mcp-ctl"
  version "${version}"
  license "MIT"

  on_macos do
    if Hardware::CPU.arm?
      url "$(url_of aarch64-apple-darwin)"
      sha256 "$(sha256_of aarch64-apple-darwin)"
    else
      url "$(url_of x86_64-apple-darwin)"
      sha256 "$(sha256_of x86_64-apple-darwin)"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "$(url_of aarch64-unknown-linux-musl)"
      sha256 "$(sha256_of aarch64-unknown-linux-musl)"
    else
      url "$(url_of x86_64-unknown-linux-musl)"
      sha256 "$(sha256_of x86_64-unknown-linux-musl)"
    end
  end

  def install
    bin.install "mcp-ctl"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/mcp-ctl --version")
  end
end
EOF
